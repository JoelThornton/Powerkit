test_that("amending an unmerged batch preserves its version and history", {
  root <- withr::local_tempdir()
  dir.create(file.path(root,"engine","news.d"),recursive=TRUE)
  dir.create(file.path(root,"app","routing","whats-new.d"),recursive=TRUE)
  writeLines(c("Package: powerkit","Version: 0.61.0"),file.path(root,"engine","DESCRIPTION"))
  writeLines("version: 0.61.0",file.path(root,"CITATION.cff"))
  writeLines(c("# powerkit 0.61.0","","* Earlier in this batch.","","# powerkit 0.60.0","","* Previous release."),file.path(root,"engine","NEWS.md"))
  writeLines(c("entries:",'  - date: "2026-11-10"','    title: "Existing"','    text: "Kept."'),file.path(root,"app","routing","whats-new.yaml"))
  writeLines("* Final safeguard.",file.path(root,"engine","news.d","last.md"))
  script <- new.env(); sys.source(file.path(repo_dir,"scripts","close-batch.R"),script)
  done <- script$close_batch("amend",root)
  expect_identical(done$version,"0.61.0")
  news <- readLines(file.path(root,"engine","NEWS.md"))
  expect_equal(sum(news == "# powerkit 0.61.0"),1)
  expect_true(all(c("* Earlier in this batch.","* Previous release.","* Final safeguard.") %in% news))
  expect_identical(readLines(file.path(root,"CITATION.cff")),"version: 0.61.0")
  writeLines("* Still waiting.",file.path(root,"engine","news.d","last.md"))
  writeLines("# powerkit 0.60.0",file.path(root,"engine","NEWS.md"))
  expect_error(script$close_batch("amend",root),"no files were changed")
  expect_true(file.exists(file.path(root,"engine","news.d","last.md")))
})
