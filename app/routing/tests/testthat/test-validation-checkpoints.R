test_that("validation shards cover the original test catalogue exactly once", {
  runner <- new.env()
  sys.source(file.path(repo_dir, "scripts", "run-validation.R"), runner)
  tests <- data.frame(id = 1:17)
  parts <- lapply(1:4, function(i) runner$validation_shard(tests, i, 4)$id)
  expect_setequal(unlist(parts), tests$id)
  expect_equal(anyDuplicated(unlist(parts)), 0L)
  expect_error(runner$validation_shard(tests, 5, 4), "cannot exceed")
  expect_error(runner$validation_shard(tests, 1, 0), "positive whole")
})

test_that("failed or unfinished validation cannot exit as a successful run", {
  runner <- new.env()
  sys.source(file.path(repo_dir, "scripts", "run-validation.R"), runner)
  expect_true(runner$validation_status_ok(c("PASS", "SKIP")))
  for (status in c("FAIL", "ERROR", "NOT RUN"))
    expect_false(runner$validation_status_ok(c("PASS", status)))
  expect_false(runner$validation_status_ok(c("PASS", "SKIP"), require_complete = TRUE))
  expect_true(runner$validation_status_ok(c("PASS", "PASS"), require_complete = TRUE))
  expect_false(runner$validation_status_ok(character()))
})

test_that("old, changed-source and changed-environment checkpoints cannot become passes", {
  runner <- new.env()
  sys.source(file.path(repo_dir, "scripts", "run-validation.R"), runner)
  path <- tempfile(fileext = ".rds")
  on.exit(unlink(path))
  row <- data.frame(result = path, test = "independent reference", index = 2L, fingerprint = "current-context")
  old <- list(test = row$test, index = 2L, status = "PASS")
  saveRDS(old, path)
  expect_null(runner$saved_result(row))
  old$fingerprint <- "other-context"
  saveRDS(old, path)
  expect_null(runner$saved_result(row))
  old$fingerprint <- row$fingerprint
  saveRDS(old, path)
  expect_identical(runner$saved_result(row)$status, "PASS")
})

test_that("checkpoint fingerprints respond to source and lock changes, not unrelated docs", {
  runner <- new.env()
  sys.source(file.path(repo_dir, "scripts", "run-validation.R"), runner)
  fixture <- tempfile("validation-context-")
  dir.create(file.path(fixture, "engine", "R"), recursive = TRUE)
  dir.create(file.path(fixture, "scripts"))
  on.exit(unlink(fixture, recursive = TRUE))
  writeLines("answer <- 1", file.path(fixture, "engine", "R", "run.R"))
  writeLines("# runner", file.path(fixture, "scripts", "run-validation.R"))
  writeLines('{"Packages": {}}', file.path(fixture, "renv.lock"))
  first <- runner$validation_fingerprint(fixture)
  expect_identical(first, runner$validation_fingerprint(fixture))
  writeLines("A documentation edit", file.path(fixture, "README.md"))
  expect_identical(first, runner$validation_fingerprint(fixture))
  writeLines("answer <- 2", file.path(fixture, "engine", "R", "run.R"))
  expect_false(identical(first, runner$validation_fingerprint(fixture)))
  second <- runner$validation_fingerprint(fixture)
  writeLines('{"Packages": {}, "R": {"Version": "different"}}', file.path(fixture, "renv.lock"))
  expect_false(identical(second, runner$validation_fingerprint(fixture)))
})
