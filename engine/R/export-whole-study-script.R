#' Write an R script that runs a whole-study simulation on your own computer
#'
#' Experimental. A whole-study simulation analyses every simulated data set
#' with every planned analysis, so a full run, and above all a search for
#' the sample size, takes far longer than the quick look the app runs. This
#' script holds the whole-study spec, with its seed, and runs
#' [run_whole_study()] on it, so it gives the same result as
#' `run_whole_study()` on the same spec with the same package versions. It
#' then saves the result and the citations next to it.
#'
#' @param spec A whole-study spec (see [validate_whole_study()]) as a named
#'   list, a JSON string or a path to a JSON file. It must give
#'   `options > seed`, so the run can be reproduced.
#' @param file Path to write the script to (UTF-8), or `NULL` to only
#'   return it.
#' @param run_time The expected run time, in words, for the script's
#'   header; `NULL` to leave it out.
#'
#' @return The script as a single string; invisibly if `file` is given.
#' @seealso [export_run_script()], the same for a single analysis.
#' @export
#' @examples
#' spec <- jsonlite::fromJSON(
#'   system.file("whole-study", "example.json", package = "powerkit"),
#'   simplifyVector = FALSE
#' )
#' spec$options$seed <- 1
#' cat(export_whole_study_script(spec))
export_whole_study_script <- function(spec, file = NULL, run_time = NULL) {
  spec <- validate_whole_study(spec)
  seed <- spec$options$seed
  if (is.null(seed)) {
    abort_export(
      "export_whole_study_script() needs a seed in the spec ('options > seed'), so the result can be reproduced."
    )
  }
  inputs <- whole_study_inputs(spec)
  backend_packages <- c("power4mome", "manymome", "lavaan", "lmhelprs")
  versions <- package_versions(c("powerkit", backend_packages))
  needs_r <- r_requirement(backend_packages)
  json <- strsplit(as.character(jsonlite::prettify(spec_to_json(unclass(spec)), indent = 2)), "\n", fixed = TRUE)[[1]]
  analyses <- vapply(spec$analyses, function(a) {
    sprintf("%s (%s)", comment_text(a$label), if (identical(a$role, "main")) "main" else "extra")
  }, character(1))
  goal <- if (identical(spec$goal$type, "sample_size")) {
    sprintf("the smallest n for %s%% power, by %s",
      format(100 * spec$goal$power), whole_study_criterion(spec, inputs)$description)
  } else {
    sprintf("the power of every analysis at n = %s", spec$goal$n)
  }
  lines <- c(
    "# Runs a powerkit whole-study simulation (experimental) on your own computer.",
    "#",
    sprintf("# Generated by powerkit %s on %s.", versions[["powerkit"]], format(Sys.Date(), "%d %B %Y")),
    sprintf("# Specification hash (SHA-256): %s", spec_hash(spec)),
    sprintf("# Analyses: %s", paste(analyses, collapse = "; ")),
    sprintf("# Goal: %s", goal),
    sprintf("# Replications: %s at each sample size simulated.", format(spec$options$nrep %||% 1000L, big.mark = ",")),
    if (!is.null(run_time)) sprintf("# Expected run time: %s.", comment_text(run_time)),
    "#",
    "# Experimental: this method has not yet been checked by a statistician.",
    "#",
    "# What you need:",
    sprintf("# * R%s, from https://cran.r-project.org", if (nzchar(needs_r)) sprintf(" %s", needs_r) else ""),
    "# * powerkit and the packages it uses. Install them once, in R, with:",
    "#     install.packages(\"remotes\")",
    "#     remotes::install_github(\"JoelThornton/Powerkit\", subdir = \"engine\")",
    sprintf(
      "#   powerkit used %s when this script was written; other versions may give",
      paste(names(versions), versions, collapse = ", ")
    ),
    "#   slightly different numbers.",
    "#",
    sprintf("# The spec below is the one you checked, with its seed (%s). The script", seed),
    "# gives the same result as powerkit's run_whole_study() on this spec and",
    "# seed. It writes two files to R's working directory (getwd()):",
    "# * powerkit-whole-study-result.rds: the result (readRDS() reads it back);",
    "# * powerkit-citations.txt: what to cite.",
    "",
    "library(powerkit)",
    "",
    "# Cores ----",
    "# More cores finish sooner (macOS and Linux). The simulation runs in batches,",
    "# so the number of cores doesn't change the result.",
    "options(powerkit.cores = 1)",
    "",
    "# The whole-study spec ----",
    r_multiline_string("spec_json", json, character()),
    "",
    "# Run it ----",
    "result <- run_whole_study(spec_json)",
    "print(result)",
    "",
    "# Save the result and the citations ----",
    "saveRDS(result, \"powerkit-whole-study-result.rds\")",
    "export_citations(result, format = \"text\", file = \"powerkit-citations.txt\")",
    "",
    "sessionInfo()"
  )
  text <- paste(c(lines, ""), collapse = "\n")
  if (is.null(file)) {
    return(text)
  }
  write_utf8(text, file)
  invisible(text)
}
