#' Write an R script that runs a power analysis on the user's own computer
#'
#' For calculations too long to run in the app (a required N for mediation,
#' and moderated mediation), the app offers this script instead of a
#' result. Unlike [export_script()], it needs no result: it holds the spec,
#' with its seed, and runs [run_spec()] on it. So it gives the same result
#' as `run_spec()` on the same spec and seed, with the same package
#' versions. It then saves the result and writes the backend-only script
#' ([export_script()]) and the citations ([export_citations()]) next to it.
#'
#' The script needs R, powerkit and the backend package installed; its
#' first lines say how, and which versions powerkit was using when the
#' script was written.
#'
#' @param spec A spec as a named list, a JSON string or a path to a JSON
#'   file. It must give `options > seed`, so the run can be reproduced.
#' @param file Path to write the script to (UTF-8), or `NULL` to only
#'   return it.
#' @param run_time The expected run time, in words (for example "about 1 to
#'   3 hours on one core"), for the script's header; `NULL` to leave it
#'   out.
#'
#' @return The script as a single string; invisibly if `file` is given.
#' @seealso [export_script()], which reproduces a result already computed.
#' @export
#' @examples
#' \donttest{
#' spec <- read_spec(system.file("specs", "mediation_parallel.json", package = "powerkit"))
#' spec$options$seed <- 1
#' cat(export_run_script(spec, run_time = "about 10 minutes on one core"))
#' }
export_run_script <- function(spec, file = NULL, run_time = NULL) {
  spec <- withCallingHandlers(
    validate_spec(spec),
    powerkit_spec_warning = function(w) invokeRestart("muffleWarning")
  )
  seed <- spec$options$seed
  if (is.null(seed)) {
    abort_export(
      "export_run_script() needs a seed in the spec ('options > seed'), so the result can be reproduced."
    )
  }
  backend <- route_spec(spec, seed)
  package <- backend$name
  versions <- package_versions(c("powerkit", backend$packages))
  needs_r <- r_requirement(backend$packages)
  json <- strsplit(as.character(jsonlite::prettify(spec_to_json(unclass(spec)), indent = 2)), "\n", fixed = TRUE)[[1]]
  batched <- !is.null(backend$batch_size)
  lines <- c(
    "# Runs a powerkit power analysis on your own computer.",
    "#",
    sprintf("# Generated by powerkit %s on %s.", versions[["powerkit"]], format(Sys.Date(), "%d %B %Y")),
    sprintf("# Design specification hash (SHA-256): %s", spec_hash(spec)),
    sprintf("# Design: %s", design_description(spec)),
    sprintf("# Goal: %s", goal_description(spec)),
    if (!is.null(run_time)) sprintf("# Expected run time: %s.", comment_text(run_time)),
    "#",
    "# What you need:",
    sprintf("# * R%s, from https://cran.r-project.org", if (nzchar(needs_r)) sprintf(" %s", needs_r) else ""),
    "# * powerkit and the packages it uses. Install them once, in R, with:",
    "#     install.packages(\"remotes\")",
    "#     remotes::install_github(\"JoelThornton/Powerkit\", subdir = \"engine\")",
    sprintf(
      "#   powerkit used %s when this script was written; other versions may give",
      paste(names(versions), versions, collapse = ", ")
    ),
    "#   slightly different numbers.",
    "#",
    sprintf("# The spec below is the one you checked, with its seed (%s). The script", seed),
    "# gives the same result as powerkit's run_spec() on this spec and seed. It",
    "# writes three files to R's working directory (getwd()):",
    "# * powerkit-result.rds: the result (readRDS() reads it back);",
    sprintf("# * powerkit-reproduce.R: a script that reproduces it with %s alone;", package),
    "# * powerkit-citations.txt: what to cite.",
    "",
    "library(powerkit)",
    "",
    "# Cores ----",
    if (batched) {
      c(
        sprintf("# More cores finish sooner (macOS and Linux). %s runs in batches, so the", package),
        "# number of cores doesn't change the result."
      )
    } else {
      c(
        "# More cores finish sooner (macOS and Linux), but change how the replications",
        "# are split, so keep 1 to get exactly the result the spec describes."
      )
    },
    "options(powerkit.cores = 1)",
    "",
    "# The design spec ----",
    r_multiline_string("spec_json", json, character()),
    "spec <- read_spec(spec_json)",
    "",
    "# Run it ----",
    "result <- run_spec(spec)",
    "print(result)",
    "",
    "# Save the result, the reproduction script and the citations ----",
    "saveRDS(result, \"powerkit-result.rds\")",
    "export_script(spec, result, file = \"powerkit-reproduce.R\")",
    "export_citations(result, format = \"text\", file = \"powerkit-citations.txt\")",
    "",
    "sessionInfo()"
  )
  text <- paste(c(lines, ""), collapse = "\n")
  if (is.null(file)) {
    return(text)
  }
  write_utf8(text, file)
  invisible(text)
}

# The R version the backend packages need, from their installed
# DESCRIPTION files ("(>= 4.4.0)"), or "" if none says.
r_requirement <- function(packages) {
  needs <- unlist(lapply(packages, function(p) {
    depends <- utils::packageDescription(p, fields = "Depends")
    if (is.na(depends)) return(NULL)
    regmatches(depends, regexpr("R \\([^)]*\\)", depends))
  }))
  if (length(needs) == 0) {
    return("")
  }
  versions <- sub("^R \\(>=\\s*([0-9.]+)\\)$", "\\1", needs)
  ok <- grepl("^[0-9.]+$", versions)
  if (!any(ok)) {
    return("")
  }
  sprintf("%s or later", max(numeric_version(versions[ok])))
}
